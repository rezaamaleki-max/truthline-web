"""
محتوای میان‌پرده‌ها — همان منطق دسکتاپ با دیالوگ‌های وابسته به روابط
"""


def get_interlude(day_key: str, relationships: dict) -> dict | None:
    """محتوای میان‌پرده‌ی مشخص بر اساس روابط فعلی"""
    if day_key == "day2":
        return _day2(relationships)
    elif day_key == "day3":
        return _day3(relationships)
    elif day_key == "day4":
        return _day4(relationships)
    return None


# ============================================================
# میان‌پرده‌ی روز دوم (پس از فاز ۱)
# ============================================================
def _day2(rel: dict) -> dict:
    li_rel = rel.get("li", 0)

    intro_line = (
        "ساعت ۰۴:۳۷ به وقت ایستگاه. سکوت راهروی بخش ناوبری را "
        "بوی فلز داغ پر کرده. نور قرمز هشدارها، از سقف روی "
        "کفپوش‌های فلزی می‌لغزد. کسی در راهرو نیست."
    )

    if li_rel >= 2:
        li_text = (
            "(با لبخند کم‌رنگ، در حالی که یک فنجان چای گرم "
            "در دست دارد) تکنسین... دیشب نخوابیدم. یه چیزی "
            "دستم اومد که فکر می‌کنم باید بدونید. راستش... "
            "نمی‌دونم چرا، ولی حس می‌کنم می‌تونم بهتون "
            "اعتماد کنم. این چند روز، یه چیزی بین ما عوض شد."
        )
    elif li_rel <= -1:
        li_text = (
            "(با فاصله، بدون نگاه مستقیم. یک لوح نمایشگر "
            "زیر بغلش گرفته) تکنسین. یه چیزی هست که باید بگم. "
            "ولی... بذارید خودم اول مطمئن بشم. بعد می‌بینم "
            "که اصلاً ارزش گفتن داره یا نه."
        )
    else:
        li_text = (
            "تکنسین... دیشب نخوابیدم. یه چیزی در پرونده‌ی "
            "محرمانه‌ی دیروز دستم اومد که فکر می‌کنم باید "
            "بدونید. اما اول باید به خودم مطمئن بشم. اگه "
            "بشه، امروز درباره‌ش حرف می‌زنیم."
        )

    outro_line = (
        "لی بدون اینکه منتظر جواب بماند، برمی‌گردد و به سمت "
        "بخش ناوبری می‌رود. صدای قدم‌هایش، در سکوت راهرو "
        "می‌پیچد. صدای فن‌ها، یکنواخت ادامه دارد."
    )

    return {
        "title": "روز دوم",
        "subtitle": "سایه‌های شک",
        "body_text": (
            "روز دوم. ایستگاه در هاله‌ای از ابهام فرو رفته. "
            "سایه‌های شک و بی‌اعتمادی میان خدمه سنگینی "
            "می‌کند. کسی مستقیم به چشم دیگری نگاه نمی‌کند."
        ),
        "image": "/assets/videos/interlude_day2.png",
        "dialogues": [
            {"speaker": "راوی", "text": intro_line},
            {"speaker": "لی", "text": li_text},
            {"speaker": "راوی", "text": outro_line},
        ],
    }


# ============================================================
# میان‌پرده‌ی روز سوم (پس از فاز ۲)
# ============================================================
def _day3(rel: dict) -> dict:
    artemis_rel = rel.get("artemis", 0)
    li_rel = rel.get("li", 0)

    intro_line = (
        "ساعت ۰۹:۱۵ به وقت ایستگاه. آفتاب مصنوعی از "
        "پنجره‌ی باریک اتاق تحلیل می‌تابد و روی کاغذهای "
        "سفید، سایه‌های کشیده می‌اندازد. یک ماگ چای سرد، "
        "کنار ترمینال مانده."
    )

    if artemis_rel >= 2:
        artemis_text = (
            "(با نگاهی صمیمانه، در حالی که پرونده‌ای را روی "
            "میز می‌گذارد) خوب شد که هستی. راستش، این چند "
            "روز که با هم کار کردیم، فهمیدم که می‌تونم روی "
            "قضاوتت حساب کنم. این پرونده رو کسی جز تو نباید "
            "ببینه."
        )
    elif artemis_rel <= -1:
        artemis_text = (
            "(با لحن رسمی و فاصله‌دار، پرونده را روی میز "
            "می‌گذارد) تکنسین. پرونده‌ی جدیدی روی میزه. "
            "روش‌شناسی تحلیل رو من تعیین می‌کنم و لطفاً قبل "
            "از هر اقدامی، با من هماهنگ کنید."
        )
    else:
        artemis_text = (
            "باید علت ریشه‌ای رو پیدا کنیم. وگرنه این فاجعه "
            "تکرار می‌شه. من با تو هستم، ولی زمان کمی داریم."
        )

    if li_rel >= 2:
        li_ref = (
            "(آرتمیس، آرام‌تر) راستی، لی هم اصرار داشت توی "
            "این مرحله کنارت باشه. گفت که بهت اعتماد داره."
        )
    elif li_rel <= -2:
        li_ref = (
            "(آرتمیس مکث می‌کند. صدایش پایین‌تر می‌آید) "
            "لی دیروز درخواست کرد که از تیم تحلیل منتقل "
            "بشه. نمی‌دونم چرا، ولی فکر می‌کنم بهتره خودت "
            "باهاش حرف بزنی."
        )
    else:
        li_ref = None

    outro = (
        "آرتمیس به سمت ترمینال برمی‌گردد و شروع می‌کند به "
        "کشیدن نمودارها. صدای تایپ، تنها صدایی است که در "
        "اتاق می‌پیچد."
    )

    dialogues = [
        {"speaker": "راوی", "text": intro_line},
        {"speaker": "دکتر آرتمیس", "text": artemis_text},
    ]
    if li_ref:
        dialogues.append(
            {"speaker": "دکتر آرتمیس", "text": li_ref}
        )
    dialogues.append({"speaker": "راوی", "text": outro})

    return {
        "title": "روز سوم",
        "subtitle": "معمای داده‌ها",
        "body_text": (
            "روز سوم. ایستگاه تثبیت شده، اما سؤالات بی‌پاسخ "
            "باقی مانده‌اند. شش فایل لاگ روی میز پراکنده‌اند "
            "— داده‌ها متناقض‌اند و ریشه‌ی واقعی بحران باید "
            "پیدا شود."
        ),
        "image": "/assets/videos/interlude_day3.png",
        "dialogues": dialogues,
    }


