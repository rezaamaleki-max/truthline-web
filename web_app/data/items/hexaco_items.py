# تابع کمکی: محاسبه نمره عامل‌ها از پاسخ‌های خام
# ============================================================
def compute_factor_scores(answers: dict) -> dict:
    """
    محاسبه نمره هر شش عامل از پاسخ‌های خام.

    Args:
        answers: دیکشنری {item_id: value} که value بین 1 تا 5 است.

    Returns:
        دیکشنری {factor_code: mean_score} که هر مقدار بین 1.00 تا 5.00 است.
    """
    factor_values = {code: [] for code in FACTORS.keys()}

    for item in HEXACO_ITEMS:
        item_id = item["id"]
        if item_id not in answers:
            continue

        raw = answers[item_id]
        # بازنمره‌گذاری گویه‌های معکوس
        value = (6 - raw) if item["reverse"] else raw
        factor_values[item["factor"]].append(value)

    scores = {}
    for code, values in factor_values.items():
        if values:
            scores[code] = round(sum(values) / len(values), 2)
        else:
            scores[code] = 0.0
    return scores