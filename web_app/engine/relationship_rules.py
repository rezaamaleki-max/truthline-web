def get_relationship_deltas(
    phase_key: str, scenario_id: str, choice_id: int
) -> dict:
    """
    دریافت تغییرات روابط برای یک انتخاب مشخص.
    Returns: dict مثل {"li": -2, "rahimi": +1}
    """
    phase_rules = RELATIONSHIP_RULES.get(phase_key, {})
    scenario_rules = phase_rules.get(scenario_id, {})
    return scenario_rules.get(choice_id, {})